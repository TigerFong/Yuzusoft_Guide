    // 新增方法：獲取特定角色的特定資訊
    get_character_info(name, infoType) {
        const character = this.get_character(name);
        if (!character) return null;
        
        switch(infoType) {
            case 'name':
                return `姓名: ${character.name}`;
            case 'age':
                return `年齡: ${character.age}`;
            case 'gender':
                return `性別: ${character.gender}`;
            case 'height':
                return `身高: ${character.height}`;
            case 'body_type':
                return `體型: ${character.body_type}`;
            case 'personality':
                return `性格: ${character.personality}`;
            case 'identity':
                return `身分: ${character.identity}`;
            case 'likes':
                return `喜好: ${character.likes.join(', ')}`;
            case 'dislikes':
                return `討厭: ${character.dislikes.join(', ')}`;
            case 'clothes':
                return `服裝: ${character.clothes.join(', ')}`;
            case 'guide_options':
                const guide = this.get_guide(name);
                if(guide && guide.getAllOptions().length > 0) {
                    return `攻略選項: ${guide.getAllOptions().map((opt, idx) => `選項${idx+1}:${opt}`).join(', ')}`;
                } else {
                    return '攻略選項: 無';
                }
            default:
                return `${infoType}: ${character[infoType] || '未知'}`;
        }
    }
    
    // 获取角色的特定攻略选项
    get_character_guide_option(characterName, optionIndex) {
        const guide = this.get_guide(characterName);
        if (!guide) return null;
        return guide.getOption(optionIndex);
    }
    
    // 获取角色的所有攻略选项
    get_character_all_guide_options(characterName) {
        const guide = this.get_guide(characterName);
        if (!guide) return [];
        return guide.getAllOptions();
    }
